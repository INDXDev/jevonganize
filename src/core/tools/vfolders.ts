/** Virtual folders: saved rules over tags, and the plans that put files in them or take them out. */
import { z } from 'zod';
import type { ToolTable } from './shared.ts';
import { fileId, fileQuery, isModel, planSource, tag } from './shared.ts';
import {
  deleteFolder,
  folderQuery,
  folderTree,
  proposeAdd,
  proposeRemove,
  ruleSchema,
  saveFolder,
} from '../vfolders.ts';

const DEFAULT_ROWS = 50;
const MODEL_MAX_ROWS = 200;
const folderId = z.int().positive();
const membership = z.strictObject({ id: folderId, file_ids: z.array(fileId).min(1) });

/** The tools on virtual folders. */
export const vfolderTools = {
  list_vfolders: {
    description:
      'Saved virtual folders as a tree, with how many files each holds. `generated` adds one folder per tag namespace and value.',
    input: z.strictObject({ generated: z.boolean().optional() }),
    writes: false,
    agent: true,
    run: async ({ generated }, { db }) => folderTree(db, generated),
  },

  save_vfolder: {
    description: 'Saves a virtual folder: a named rule over tags. Changes no tag.',
    input: z.strictObject({
      id: folderId.optional(),
      name: z.string(),
      parent: folderId.nullable().optional(),
      rule: ruleSchema.partial(),
      tag: tag.nullable().optional(),
    }),
    writes: true,
    agent: false,
    run: async (input, { db }) => saveFolder(db, input),
  },

  delete_vfolder: {
    description: 'Deletes a virtual folder and the folders under it. Files and tags stay.',
    input: z.strictObject({ id: folderId }),
    writes: true,
    agent: false,
    run: async ({ id }, { db }) => deleteFolder(db, id),
  },

  vfolder_files: {
    description:
      'The files in a virtual folder, saved by `id` or generated by its key, with the query that finds them.',
    input: fileQuery
      .pick({ hide_dotfiles: true, sort: true, order: true, limit: true, offset: true })
      .extend({ id: folderId.optional(), generated: tag.optional() }),
    writes: false,
    agent: true,
    run: async ({ id, generated, ...page }, ctx) => {
      const query = folderQuery(ctx.db, { id, generated });
      const limit = page.limit ?? DEFAULT_ROWS;
      const allowed = isModel(ctx) ? Math.min(limit, MODEL_MAX_ROWS) : limit;
      return { ...ctx.db.searchFiles({ ...query, ...page, limit: allowed }), query };
    },
  },

  add_to_vfolder: {
    description:
      'Stores a plan that adds the folder’s home tag to files, so they collect in it. Changes no tag until a person applies it.',
    input: membership,
    writes: true,
    agent: true,
    run: async ({ id, file_ids }, ctx) => proposeAdd(ctx.db, id, file_ids, planSource(ctx)),
  },

  remove_from_vfolder: {
    description:
      'Stores a plan that removes the folder’s home tag from files. Changes no tag until a person applies it.',
    input: membership,
    writes: true,
    agent: true,
    run: async ({ id, file_ids }, ctx) => proposeRemove(ctx.db, id, file_ids, planSource(ctx)),
  },
} satisfies Partial<ToolTable>;
